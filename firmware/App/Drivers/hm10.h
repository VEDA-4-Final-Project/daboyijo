/*
 * hm10.h — HM-10 BLE 송신 모듈 (인터페이스)
 *
 * STM32(웨어러블) → HM-10 → BLE → 중계 노드(RPi)
 * 투과모드라 UART 로 바이트만 밀어내면 그대로 BLE 로 넘어감
 *
 * 사용법:
 *   1) main.c에서 #include "hm10.h"
 *   2) UART 초기화 후 hm10_init(&huart2);  한 번 호출
 *   3) 이후 hm10_send_packet(...) 로 7바이트 패킷 송신
 *
 * ── BLE 바이너리 패킷 구조 (7바이트, 팀 공용 스펙) ──────────────
 *   [0] 0xAA           패킷 시작 헤더 (프레이밍 식별자)
 *   [1] heart_rate     심박수 (bpm)      0~255
 *   [2] spo2           산소포화도 (%)    0~100
 *   [3] fall_flag      낙상 의심 플래그  0x00 정상 / 0x01 의심
 *   [4] steps_lo       걸음 수 하위 바이트 (리틀엔디언 uint16)
 *   [5] steps_hi       걸음 수 상위 바이트
 *   [6] checksum       [0]~[5] 전체의 XOR
 * ────────────────────────────────────────────────────────────
 *
 * 체온 필드는 제거했다. 측정 하드웨어가 없어 계속 0 더미만 실려 나갔고,
 * 그 0 때문에 수신 측의 체온 기반 판정(서버 40도 알람, Qt 38도 위험)이
 * 애초에 발동한 적이 없다. 자리만 차지하던 바이트라 없앤다.
 *
 * ── 체크섬이 하는 일 (그리고 하지 않는 일) ──────────────────────
 *
 * 이건 전송 오류 검출용이 아니다. BLE 는 링크 계층에서 이미 CRC 와 재전송으로
 * 무결성을 보장하므로 깨진 바이트가 올라올 일이 거의 없다.
 *
 * 진짜 목적은 프레이밍이다. 수신 측은 0xAA 를 찾아 동기를 잡는데, 데이터
 * 바이트에도 0xAA(170)가 얼마든지 나올 수 있다 — 걸음 수 170, 426, 682…
 * 가짜 헤더에 물리면 그 뒤로 계속 어긋난 채 읽는다. 체크섬은 잘못 잡은 동기를
 * 즉시 알아채 1바이트 밀고 재동기하게 해 준다.
 *
 * XOR 을 쓴 이유는 단순해서다. 무작위 구간이 우연히 통과할 확률은 1/256 으로
 * CRC-8 과 같고(1바이트 검사의 한계), 대신 수신 측을 어떤 언어로 다시 짜도
 * 세 줄이면 끝난다. 오정렬이 실제로 문제가 될 만큼 잦아지면 그때 폭을 늘릴 것.
 *

 
 * ⚠ 수신 측과 반드시 동시에 배포할 것.
 *   relay-node/src/main_relay.cpp 의 PKT_LEN 이 이 길이와 같아야 한다.
 *   릴레이만 7 로 올리면 5바이트 패킷을 기다리다 다음 패킷 헤더까지
 *   현재 패킷으로 삼켜 프레이밍이 통째로 어긋난다. 반대 방향(펌웨어만 7)은
 *   남는 2바이트가 버려지다 걸음 수 하위 바이트가 0xAA(170)일 때 가짜 헤더로
 *   오인된다 — 어느 쪽이든 한쪽만 올리면 안 된다.
 */
#ifndef HM10_H
#define HM10_H

#include "stm32f4xx_hal.h"
#include <stdint.h>

/* 송신 패킷 상수 (STM32 → RPi) */
#define HM10_PKT_HEADER   0xAA
#define HM10_PKT_LEN      7

/* ── 수신 패킷 (RPi → STM32) — 시각 동기 ────────────────────────
 *   [0] 0x55       헤더
 *   [1] hour       0~23
 *   [2] minute     0~59
 *   [3] second     0~59
 *   [4] checksum   [0]~[3] 의 XOR
 *
 * 헤더를 송신용 0xAA 와 다른 값으로 둔 이유: UART 는 전이중이라 실제 충돌은
 * 없지만, 로그를 볼 때 방향이 한눈에 구분되고 나중에 명령을 더 추가할 때
 * 두 방향의 규격이 섞이지 않는다.
 * ──────────────────────────────────────────────────────────── */
#define HM10_RX_HEADER    0x55
#define HM10_RX_PKT_LEN   5

/* 낙상 의심 플래그 값 */
#define HM10_FALL_NONE    0x00
#define HM10_FALL_SUSPECT 0x01

/* HM-10 이 연결된 UART 핸들 등록 (부팅 시 1회) */
void hm10_init(UART_HandleTypeDef *huart);

/* 7바이트 바이너리 패킷 송신 (체크섬은 내부에서 계산해 붙인다)
 *   hr        : 심박수 bpm      (0~255, 범위 밖은 클램프)
 *   spo2      : 산소포화도 %    (0~100, 범위 밖은 클램프)
 *   fall_flag : 낙상 의심 0/1   (0 이외 값은 1로 정규화)
 *   steps     : 걸음 수 0~65535 (리틀엔디언 2바이트로 실린다)
 *  → 전송 예: AA 4E 62 01 E8 03 6C  (78bpm, 98%, 낙상의심, 1000걸음) */
void hm10_send_packet(uint8_t hr, uint8_t spo2, uint8_t fall_flag, uint16_t steps);

/* 수신 개시. hm10_init() 뒤에 한 번 부르면 이후에는 스스로 재무장한다.
 * 1바이트씩 인터럽트로 받아 0x55 를 기준으로 패킷을 맞춘다 — 고정 길이로
 * 통째로 받으면 바이트 하나만 유실돼도 이후 모든 패킷이 영구히 어긋난다. */
void hm10_start_receive(void);

/**
  * 수신해 둔 시각을 꺼낸다 (있으면 1, 없으면 0).
  *
  * ISR 은 검증만 하고 값을 남겨두며, 실제 반영은 메인 루프가 이 함수로 꺼내
  * AppClock_SetTime() 에 넘기는 방식이다. ISR 안에서 시계를 직접 만지지 않아
  * 다른 인터럽트 처리와 뒤엉킬 여지를 없앤다.
  */
uint8_t hm10_take_time(uint8_t *hour, uint8_t *minute, uint8_t *second);

#endif /* HM10_H */
